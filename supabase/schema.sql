-- Collection de télécartes : à exécuter une fois dans Supabase > SQL Editor.
-- Lecture publique, écriture réservée aux comptes listés dans la table admins.

create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.admins enable row level security;
-- Aucune policy sur admins : la table n'est lisible que via is_admin().

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

create table if not exists public.puces (
  code text primary key,
  image_url text,
  description text
);

create table if not exists public.cartes (
  id bigint generated by default as identity primary key,
  reference text not null,
  puce text not null,
  unites integer,
  nom text not null,
  date_emission date,
  tirage bigint check (tirage is null or tirage >= 0),
  cote numeric(8, 2) check (cote is null or cote >= 0),
  serie text,
  image_recto text,
  image_verso text,
  image_source text,
  notes text,
  a_verifier jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cartes_type_unique unique nulls not distinct (reference, puce, unites)
);
create index if not exists cartes_reference_idx on public.cartes (reference);

-- Un exemplaire = une carte physique. L'indice donne sa place dans le classeur :
-- page = (indice - 1) / taille_page + 1, case = (indice - 1) % taille_page + 1.
create table if not exists public.exemplaires (
  id bigint generated by default as identity primary key,
  carte_id bigint not null references public.cartes (id) on delete cascade,
  indice integer not null check (indice > 0),
  etat text check (etat in ('U', 'L')),
  date_ajout date not null default current_date,
  sorti_le date,
  sortie_note text
);
create index if not exists exemplaires_carte_idx on public.exemplaires (carte_id);
create unique index if not exists exemplaires_indice_actif_idx
  on public.exemplaires (indice) where sorti_le is null;

create table if not exists public.souhaits (
  id bigint generated by default as identity primary key,
  reference text not null,
  nom text,
  note text,
  created_at timestamptz not null default now()
);

-- Référentiel servant à préremplir le formulaire d'ajout.
create table if not exists public.catalogue (
  id bigint generated by default as identity primary key,
  reference text not null,
  puce text,
  unites integer,
  nom text,
  date_emission date,
  tirage bigint,
  cote numeric(8, 2),
  image_url text,
  source text,
  source_id text,
  constraint catalogue_unique unique nulls not distinct (reference, puce, unites, source)
);
create index if not exists catalogue_reference_idx on public.catalogue (reference);
create index if not exists catalogue_reference_motif_idx on public.catalogue (reference text_pattern_ops);

create or replace function public.touch_updated_at()
returns trigger language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists cartes_touch on public.cartes;
create trigger cartes_touch before update on public.cartes
  for each row execute function public.touch_updated_at();

-- Droits : tout le monde lit, seul un admin écrit.
do $$
declare t text;
begin
  foreach t in array array['puces', 'cartes', 'exemplaires', 'souhaits', 'catalogue'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists lecture_publique on public.%I', t);
    execute format('create policy lecture_publique on public.%I for select using (true)', t);
    execute format('drop policy if exists ecriture_admin on public.%I', t);
    execute format(
      'create policy ecriture_admin on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      t
    );
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

grant execute on function public.is_admin() to anon, authenticated;

-- Visuels : lecture publique, écriture admin.
insert into storage.buckets (id, name, public)
values ('visuels', 'visuels', true)
on conflict (id) do nothing;

drop policy if exists visuels_lecture on storage.objects;
create policy visuels_lecture on storage.objects
  for select using (bucket_id = 'visuels');

drop policy if exists visuels_ecriture on storage.objects;
create policy visuels_ecriture on storage.objects
  for all to authenticated
  using (bucket_id = 'visuels' and public.is_admin())
  with check (bucket_id = 'visuels' and public.is_admin());

